// Haversine formula for live approximate driving distance (with road tortuosity factor ~1.25)
export function calculateRoadDistanceBetweenCoords(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): { distanceKm: number; distanceMiles: number } {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const directKm = R * c;

  // Real highways are typically ~20-30% longer than great-circle straight lines
  const drivingKm = Math.round(directKm * 1.25);
  const drivingMiles = Math.round(drivingKm * 0.621371);

  return { distanceKm: Math.max(10, drivingKm), distanceMiles: Math.max(6, drivingMiles) };
}
